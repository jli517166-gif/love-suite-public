import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { performance } from 'node:perf_hooks';
import { commitCoreMemory, readCoreMemory } from '../core-memory.js';
import { legacyCandidates, auxiliaryLegacyNodes } from '../legacy-memory.js';
const search = await import('../memory-search.js').catch(() => ({}));
assert.equal(typeof search.searchMemories, 'function', '需要统一核心和旧库的当前记忆检索');
const workspace = fs.mkdtempSync(path.join(os.tmpdir(), 'love-search-'));
process.env.LOVE_TEST_ISOLATED = '1';
process.env.LOVE_COMPANION_CONFIG = path.join(workspace, 'runtime.json');
const put = (relative, value) => { const file = path.join(workspace, relative); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, typeof value === 'string' ? value : JSON.stringify(value)); };
const memory = (ref, content, coreId = 'self') => ({ op: 'record_memory', ref, coreId, content, kind: 'preference', epistemic: 'reported', importance: 3, reason: '隔离模块测试', source: { kind: 'conversation', reference: 'fixture#user' } });
try {
  const first = commitCoreMemory(workspace, { expectedRevision: 0, operations: [
    { op: 'create_core', ref: '$core', title: '出行准备', summary: '出门前的约定', reason: '归类', evidenceIds: ['$check'] },
    memory('$check', '离开房间前检查门窗', '$core'), memory('$tea', '我喜欢雨天喝橙花茶'), memory('$friend', '小岚住在海边'),
    { op: 'link', ref: '$link', source: '$tea', target: '$friend', relation: '一起喝茶', reason: '明确关联' },
  ] });
  put('memory/profile.json', { likes: ['柚子'], facts: { 城市: '青岛' } });
  put('memory/learning.json', { items: [{ name: '折纸', note: '先折对角线', source: 'user' }] });
  put('memory/journal/2020-01-01.md', '# 2020-01-01\n- 当天一起看了极光\n');
  const query = (text, extra = {}) => search.searchMemories(workspace, text, { semanticEnabled: false, ...extra });
  assert.ok((await query('出行')).items.some(m => m.id === first.references.$check));
  assert.ok((await query('中意')).items.some(m => m.id === first.references.$tea), '已有同义词扩展也适用核心');
  assert.ok((await query('极光')).items.some(m => m.layer === 'journal'), '旧日记不被90天或图谱900节点窗口截断');
  assert.ok((await query('折纸')).items.some(m => m.layer === 'learning'));
  assert.ok((await query('青岛')).items.some(m => m.layer === 'profile'));
  const { DatabaseSync } = await import('node:sqlite');
  fs.mkdirSync(path.join(workspace, '.dsh-meow'), { recursive: true });
  const database = new DatabaseSync(path.join(workspace, '.dsh-meow/memory.db'));
  database.exec('CREATE TABLE fact(id TEXT,content TEXT,keywords TEXT,status TEXT)');
  database.prepare('INSERT INTO fact VALUES (?,?,?,?)').run('duplicate', '离开房间前检查门窗', '["安保"]', 'active');
  database.close();
  const metadataHit = await query('安保');
  assert.equal(metadataHit.items[0]?.id, first.references.$check, '同文去重后必须保留旧来源独有关键词');
  assert.equal(metadataHit.items[0].sourceRefs.length, 2);
  const legacy = legacyCandidates({ nodes: auxiliaryLegacyNodes({ likes: ['柚子'] }) }, readCoreMemory(workspace)).candidates[0];
  const tea = await query('橙花茶');
  assert.ok(tea.items.some(m => m.id === first.references.$friend && m.matchBy.includes('relation')));
  assert.match(search.formatMemorySearch(tea, '橙花茶'), /fixture#user|直接关联/);
  const change = commitCoreMemory(workspace, { expectedRevision: 1, operations: [memory('$new', '我现在喜欢薄荷茶'), { op: 'supersede_memory', id: first.references.$tea, replacementId: '$new', source: { kind: 'conversation', reference: 'fixture#change' }, epistemic: 'reported', reason: '明确修正' }] });
  assert.ok(!(await query('橙花茶')).items.some(m => m.id === first.references.$tea));
  assert.ok((await query('薄荷茶')).items.some(m => m.id === change.references.$new));
  const adopted = commitCoreMemory(workspace, { expectedRevision: 2, operations: [{ op: 'adopt_legacy', ref: '$adopted', legacyId: legacy.legacyId, coreId: 'self', kind: 'preference', importance: 3, reason: '兼容迁移' }] }, { legacyCandidates: [legacy] });
  assert.equal((await query('柚子')).items.filter(m => m.content.includes('柚子')).length, 1);
  commitCoreMemory(workspace, { expectedRevision: 3, operations: [{ op: 'archive', id: adopted.references.$adopted, reason: '归档不复活旧档案' }] });
  assert.equal((await query('柚子')).items.length, 0);
  put('memory/groups/12345678/group.json', { members: {}, notes: [{ text: '本群喜欢柚子' }] });
  put('memory/groups/23456789/group.json', { members: {}, notes: [{ text: '别群私密柚子' }] });
  const group = await query('柚子', { groupId: '12345678' });
  assert.equal(group.items.length, 1);
  assert.match(group.items[0].content, /本群/);
  assert.doesNotMatch(JSON.stringify(group), /青岛|别群|橙花茶/);
  const semantic = await query('航海', { semanticEnabled: true, semanticRank: async (_q, items) => [{ item: { id: first.references.$check, text: '伪造内容' }, score: .9 }, { item: { id: 'outside-scope' }, score: 1 }] });
  assert.ok(semantic.items.some(m => m.id === first.references.$check && m.content === '离开房间前检查门窗'));
  assert.ok(!semantic.items.some(m => m.id === 'outside-scope'));
  const fail = await query('出行', { semanticEnabled: true, semanticRank: async () => { throw new Error('SECRET_ERROR'); } });
  assert.ok(fail.items.some(m => m.id === first.references.$check)); assert.equal(fail.metrics.semanticStatus, 'failed');
  let release;
  const timeout = await query('出行', { semanticEnabled: true, semanticRank: () => new Promise(resolve => { release = resolve; }), semanticTimeoutMs: 20 });
  assert.equal(timeout.metrics.semanticStatus, 'timeout');
  const busy = await query('出行', { semanticEnabled: true, semanticRank: () => { throw new Error('busy时不能再次发起'); } });
  assert.equal(busy.metrics.semanticStatus, 'busy'); release([]); await Promise.resolve();
  assert.equal((await query('不存在的超导飞行器')).items.length, 0);
  assert.equal((await query('？！')).items.length, 0, '没有可检索词不能把近期条目冒充命中');
  put('memory/life.jsonl', JSON.stringify({ date: '2020-01-01', text: '长文起点' + '背景'.repeat(2500) + '尾部暗号彗星' }) + '\n');
  const long = await query('彗星');
  assert.ok(long.items.some(m => m.content.includes('彗星')));
  assert.match(search.formatMemorySearch(long, '彗星'), /截断/);
  assert.equal(readCoreMemory(workspace).revision, 4, '检索不改写记忆');
  const start = performance.now(); for (let i = 0; i < 3; i++) await query('出行');
  console.log('ok   统一检索：核心/旧库、归属词/同义词、一跳关联、当前过滤、群隔离、语义边界/降级和长文；3次小库检索ms=' + (performance.now() - start).toFixed(1));
  const operations = [];
  for (let i = 0; i < 5; i++) operations.push(memory(`$neighbor${i}`, `独立关联条目${i}`), { op: 'link', ref: `$edge${i}`, source: first.references.$check, target: `$neighbor${i}`, relation: '测试直接关联', reason: '测试范围上限' });
  commitCoreMemory(workspace, { expectedRevision: 4, operations });
  assert.equal((await query('出行')).items.filter(item => item.matchBy.includes('relation')).length, 3);
  put('memory/life.jsonl', Array.from({ length: 1200 }, (_, i) => JSON.stringify({ date: '2020-01-01', text: `本地规模条目${i}；${i === 0 ? '早期珍珠暗号' : '普通独立内容'}` })).join('\n') + '\n');
  const big = await query('珍珠');
  assert.ok(big.items.some(item => item.content.includes('早期珍珠暗号')));
  assert.ok(big.metrics.totalCandidates >= 1200);
  const bounded = await query('珍珠', { semanticEnabled: true, semanticRank: async (_q, items) => { assert.ok(items.length <= 256); assert.ok(items.every(item => typeof item.text === 'string' && item.text.length <= 4000)); return []; } });
  console.log('ok   规模证据：' + JSON.stringify(bounded.metrics));
  put('custom/memory/profile.json', { nickname: 'CUSTOM_PRIVATE' });
  put('custom/memory/groups/12345678/group.json', { members: {}, notes: [{ text: 'CUSTOM_GROUP 柚子' }] });
  put('runtime.json', { workspace, channel: 'none', proactiveEnabled: false, reflectionBackgroundEnabled: false, semanticEnabled: false, groupWorkspaces: { '12345678': path.join(workspace, 'custom') } });
  const { buildRecall, apply } = await import('../index.js');
  assert.match(await buildRecall(workspace, 7, { semanticEnabled: false }, '出行'), /离开房间前检查门窗/);
  assert.match(await buildRecall(workspace, 7, { semanticEnabled: false }, '折纸'), /先折对角线/);
  const tools = new Map();
  const dispose = await apply({ tools: { register(tool) { tools.set(tool.name, tool); } }, on() {}, logger: { info() {}, warn() {} } }, { workspace, channel: 'none', proactiveEnabled: false, reflectionBackgroundEnabled: false, semanticEnabled: false });
  try {
    const response = await tools.get('love_recall').execute({ query: '柚子' }, { agent: { session: { id: 'qq-group-12345678', header: { cwd: workspace } } } });
    assert.match(response.text, /CUSTOM_GROUP/); assert.doesNotMatch(response.text, /CUSTOM_PRIVATE|青岛|别群|薄荷茶/);
    assert.match(await buildRecall(workspace, 7, { groupMemoryEnabled: false }, '柚子', { groupId: '12345678', workspace: path.join(workspace, 'custom') }), /群记忆已关闭/);
  } finally { dispose?.(); }
  console.log('ok   宿主工具：统一query分支、当前群自定义目录、群关闭与私聊/别群隔离');
} finally { assert.equal(path.dirname(workspace), path.resolve(os.tmpdir())); fs.rmSync(workspace, { recursive: true, force: true }); }
