/** Dev-only deterministic build. Installed plugins use the committed single file. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "plugin/client.js");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["plugin/client-src/index.js"],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: ["chrome120"],
  external: ["react"],
  charset: "utf8",
  legalComments: "none",
  banner: {
    js: '// Generated by scripts/build-client.mjs. Edit plugin/client-src instead.\nwindow.__ModuleLoader__.load({id:"dsh-memory-network",factory:(require)=>{\nconst module={exports:{}};',
  },
  footer: { js: "return module.exports;\n}});" },
});
const text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const actual = fs.existsSync(output) ? fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") : "";
  if (actual !== text) {
    console.error("面板构建产物过期：npm run build:client");
    process.exitCode = 1;
  } else console.log("ok   面板产物与锁定构建器生成内容一致");
} else {
  fs.writeFileSync(output, text);
  console.log("Built plugin/client.js");
}
